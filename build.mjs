import { readFile, writeFile } from "node:fs/promises";

// Produce one packaged classic content script, avoiding cross-origin module
// requests from YouTube. No dependency downloads or external build tools.
const inputs = ["voice-recorder.mjs", "voice-codec.mjs", "microphone-inputs.mjs", "page-recorder-host.mjs", "recording-entry.js"];
const sources = [];
for (const name of inputs) {
  const source = (await readFile(new URL(name, import.meta.url), "utf8"))
    .replace(/^import .* from .*;\r?\n/gm, "")
    .replace(/^export /gm, "");
  if (/^\s*(?:import|export)\s/m.test(source) || /\bimport\s*\(/.test(source)) {
    throw new Error(`Unsupported module syntax in ${name}`);
  }
  sources.push(`// Source: ${name}\n${source}`);
}
await writeFile(new URL("recording-content.js", import.meta.url),
  `// Generated by build.mjs. Edit the source modules, then run node build.mjs.\n(() => {\n"use strict";\n${sources.join("\n")}\n})();\n`);
